#!/usr/bin/env python3
"""Generates Iron Ring's NES-style sound effects and music into Assets/Resources/Audio/.

    python3 Tools/Audio/generate_audio.py            # everything
    python3 Tools/Audio/generate_audio.py --check    # compare with the committed files (CI)
    python3 Tools/Audio/generate_audio.py --preview build/audio   # also write the themes as WAV

Effects: 44.1 kHz mono 16-bit WAV, deterministic to the byte. Music: Ogg Vorbis
(encoded with ffmpeg + libvorbis) plus music.json with the loop point and the
SHA-256 of the rendered PCM. Lossy encoders differ between versions, so --check
compares the PCM hash, and the OGG is re-encoded only when the music changes.
See docs/audio.md.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import shutil
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from chiptune import apu, sfx, voice  # noqa: E402
from chiptune.themes import lantern_row, menu, pier_nine, the_crown  # noqa: E402

ROOT = HERE.parent.parent
AUDIO = Path("Resources") / "Audio"
GAIN = 1.2            # chip output -> 16-bit full scale; same for every file, so levels stay relative
# One theme per venue (keys are the stage ids in Assets/Data/stages.json -> music),
# plus the front end's (GameSettings.json -> ui.music).
THEMES = {"pier_nine": pier_nine, "lantern_row": lantern_row, "the_crown": the_crown, "menu": menu}
MUSIC_GAIN = 0.5
VORBIS_QUALITY = 5


def pcm16(samples: np.ndarray) -> np.ndarray:
    scaled = np.round(samples * GAIN * 32767)
    if np.max(np.abs(scaled)) > 32767:
        raise SystemExit(f"clipping ({np.max(np.abs(scaled)) / 32767:.2f} x full scale): lower GAIN")
    return scaled.astype(np.int16)


def wav_bytes(pcm: np.ndarray) -> bytes:
    out = io.BytesIO()
    with wave.open(out, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(apu.SAMPLE_RATE)
        w.writeframes(pcm.astype("<i2").tobytes())
    return out.getvalue()


def trim_tail(pcm: np.ndarray, threshold: int = 24) -> np.ndarray:
    """Drops the silent tail (filters ring out a little past the last frame)."""
    loud = np.nonzero(np.abs(pcm) > threshold)[0]
    end = int(loud[-1]) + 1 + apu.SAMPLE_RATE // 100 if len(loud) else 1
    out = pcm[:end].copy()
    fade = min(len(out), apu.SAMPLE_RATE // 200)
    out[-fade:] = (out[-fade:] * np.linspace(1, 0, fade)).astype(np.int16)
    return out


def render_effects() -> dict[Path, bytes]:
    return {AUDIO / f"{name}.wav": wav_bytes(trim_tail(pcm16(apu.render(build()))))
            for name, build in sfx.EFFECTS.items()}


VOICE_PEAK_DBFS = -3.0


def render_voice() -> dict[Path, bytes]:
    """Announcer lines (eSpeak NG through the DMC model), each normalised to the same peak."""
    speaker = voice.Speaker()
    files = {}
    for name, line in voice.LINES.items():
        samples = voice.render(speaker, line)
        gain = 10 ** (VOICE_PEAK_DBFS / 20) / (float(np.max(np.abs(samples))) or 1.0)
        pcm = np.round(samples * gain * 32767).astype(np.int16)
        files[AUDIO / "Voice" / f"{name}.wav"] = wav_bytes(trim_tail(pcm))
    return files


def render_music() -> tuple[dict[str, np.ndarray], dict]:
    pcm: dict[str, np.ndarray] = {}
    entries = {}
    for theme_id, module in THEMES.items():
        score, loop_row = module.build()
        music = pcm16(apu.render(score.render_channels()))
        pcm[theme_id] = music
        entries[theme_id] = {
            "title": module.TITLE, "file": f"theme_{theme_id}.ogg", "sampleRate": apu.SAMPLE_RATE,
            "loopStartFrame": loop_row * score.frames_per_row * apu.SAMPLES_PER_FRAME,
            "lengthFrames": int(len(music)), "gain": MUSIC_GAIN,
            "pcmSha256": hashlib.sha256(music.astype("<i2").tobytes()).hexdigest(),
        }
    meta = {"$comment": "Generated by Tools/Audio/generate_audio.py. One theme per stage id, and menu; "
                        "frames are sample frames at sampleRate.",
            "themes": entries}
    return pcm, meta


def committed_meta(path: Path) -> dict:
    try:
        return json.loads(path.read_text()).get("themes", {})
    except (OSError, ValueError):
        return {}


def meta_bytes(meta: dict) -> bytes:
    return (json.dumps(meta, indent=2) + "\n").encode()


def encode_vorbis(pcm: np.ndarray, target: Path) -> None:
    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        raise SystemExit("ffmpeg (with libvorbis) is needed to encode the music")
    with tempfile.TemporaryDirectory() as tmp:
        source = Path(tmp) / "theme.wav"
        source.write_bytes(wav_bytes(pcm))
        subprocess.run([ffmpeg, "-v", "error", "-y", "-i", str(source), "-c:a", "libvorbis",
                        "-q:a", str(VORBIS_QUALITY), "-map_metadata", "-1", "-fflags", "+bitexact",
                        str(target)], check=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--assets", type=Path, default=ROOT / "Assets")
    parser.add_argument("--check", action="store_true", help="fail if committed files differ")
    parser.add_argument("--preview", type=Path, help="also write the themes as WAV here")
    args = parser.parse_args()

    effects = render_effects() | render_voice()
    music, meta = render_music()
    meta_path = args.assets / AUDIO / "music.json"
    previous = committed_meta(meta_path)

    def current(theme_id: str) -> bool:
        entry, old = meta["themes"][theme_id], previous.get(theme_id, {})
        return old.get("pcmSha256") == entry["pcmSha256"] and (args.assets / AUDIO / entry["file"]).exists()

    if args.check:
        stale = [str(p) for p, data in effects.items()
                 if not (args.assets / p).exists() or (args.assets / p).read_bytes() != data]
        stale += [f"{AUDIO / meta['themes'][t]['file']} (the rendered theme changed)" for t in THEMES if not current(t)]
        if not meta_path.exists() or meta_path.read_bytes() != meta_bytes(meta):
            stale.append(str(AUDIO / "music.json"))
        for p in stale:
            print(f"FAIL: {p} differs from generate_audio.py output (regenerate)")
        print("audio check: " + ("FAILED" if stale else "ok"))
        return 1 if stale else 0

    for path, data in effects.items():
        target = args.assets / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        print(f"audio: {path} ({len(data) // 1024} KiB)")
    for theme_id, entry in meta["themes"].items():
        target = args.assets / AUDIO / entry["file"]
        if current(theme_id):
            print(f"audio: {AUDIO / entry['file']} unchanged")
        else:
            encode_vorbis(music[theme_id], target)
            print(f"audio: {AUDIO / entry['file']} ({target.stat().st_size // 1024} KiB, re-encoded)")
        if args.preview:
            args.preview.mkdir(parents=True, exist_ok=True)
            (args.preview / f"theme_{theme_id}.wav").write_bytes(wav_bytes(music[theme_id]))
    meta_path.write_bytes(meta_bytes(meta))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
