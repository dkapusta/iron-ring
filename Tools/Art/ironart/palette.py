def rgb(name: str) -> tuple[int, int, int]:
    return hex_rgb(COLOURS[name])


def ramp(name: str) -> list[tuple[int, int, int]]:
    return [hex_rgb(c) for c in RAMPS[name]]


def write_palette_files(directory: Path) -> None:
    """Writes palette.json and a GIMP palette (palette.gpl) for artists."""
    directory.mkdir(parents=True, exist_ok=True)
    data = {
        "$comment": "Iron Ring palette. Generated by Tools/Art/generate.py; see docs/art/asset-spec.md.",
        "colours": COLOURS,
        "ramps": RAMPS,
    }
    (directory / "palette.json").write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")

    lines = ["GIMP Palette", "Name: Iron Ring", "Columns: 8", "#"]
    for name, value in COLOURS.items():
        r, g, b = hex_rgb(value)
        lines.append(f"{r:3d} {g:3d} {b:3d}\t{name}")
    for name, values in RAMPS.items():
        for i, value in enumerate(values):
            r, g, b = hex_rgb(value)
            lines.append(f"{r:3d} {g:3d} {b:3d}\t{name}_{i}")
    (directory / "palette.gpl").write_text("\n".join(lines) + "\n", encoding="utf-8")
