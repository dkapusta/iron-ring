"""Renders every fighter frame, packs the atlas and draws the HUD portrait."""

from __future__ import annotations

import json
from pathlib import Path

from PIL import Image

from . import atlas, palette
from .characters import CHARACTERS, Character
from .figure import Canvas
from .poses import PoseBook

CANVAS = (320, 240)
ORIGIN = (150, 228)


def render_frames(character: Character) -> tuple[list[atlas.Frame], dict[str, dict]]:
    frames: list[atlas.Frame] = []
    points: dict[str, dict] = {}
    for name, pose in PoseBook(character).frames().items():
        canvas = Canvas(CANVAS[0], CANVAS[1], ORIGIN)
        s = character.draw(canvas, pose)
        frames.append(atlas.trim(name, canvas.render(), ORIGIN, pose.partner))
        points[name] = {k: [round(v[0], 1), round(v[1], 1)] for k, v in
                        (("near_wrist", s.near_wrist), ("far_wrist", s.far_wrist), ("near_toe", s.near_toe),
                         ("head", s.head))}
    return frames, points


def portrait(character: Character, size: int = 32) -> Image.Image:
    """Head-and-shoulders crop of the idle pose on a dark, lamp-lit backdrop."""
    pose = PoseBook(character).frames()["idle_0"]
    canvas = Canvas(CANVAS[0], CANVAS[1], ORIGIN)
    s = character.draw(canvas, pose)
    figure = canvas.render()
    cx = int(ORIGIN[0] + s.head[0]) - 2
    cy = int(ORIGIN[1] - s.head[1]) + 5
    crop = figure.crop((cx - size // 2, cy - size // 2, cx + size // 2, cy + size // 2))
    back = Image.new("RGBA", (size, size), palette.rgb("night_1") + (255,))
    glow = palette.rgb("sodium_1")
    for y in range(size):  # warm light from above, ordered dither
        for x in range(size):
            t = 1 - y / size
            threshold = ((x % 2) * 2 + (y % 2) * 3) % 4 / 4
            if t * 0.6 > threshold + 0.25:
                back.putpixel((x, y), glow + (255,))
    back.alpha_composite(crop)
    return back


def generate(assets: Path, report: Path | None = None) -> None:
    for cid, character in CHARACTERS.items():
        folder = assets / "Fighters" / cid.capitalize()
        frames, points = render_frames(character)
        atlas.write(frames, folder / f"{cid}_atlas.png",
                    extra={"$comment": "Generated by Tools/Art/generate.py. Frame names: docs/art/asset-spec.md."})
        portrait(character).save(folder / f"{cid}_portrait.png", optimize=True)
        if report is not None:
            report.mkdir(parents=True, exist_ok=True)
            (report / f"{cid}_points.json").write_text(json.dumps(points, indent=1), encoding="utf-8")
        print(f"fighters: {cid}: {len(frames)} frames")
        if sunk := atlas.below_floor(frames):
            print(f"fighters: {cid}: WARNING below the floor: {', '.join(sunk)}")
