CHARSET = "".join(GLYPHS)
COLUMNS = 16


def glyph_mask(ch: str) -> list[list[bool]]:
    return [[cell == "#" for cell in row] for row in GLYPHS[ch]]


def _sheet(cell_w: int, cell_h: int) -> Image.Image:
    rows = (len(CHARSET) + COLUMNS - 1) // COLUMNS
    return Image.new("RGBA", (cell_w * COLUMNS, cell_h * rows), (0, 0, 0, 0))


def small_atlas() -> Image.Image:
    img = _sheet(6, 8)
    for i, ch in enumerate(CHARSET):
        ox, oy = (i % COLUMNS) * 6, (i // COLUMNS) * 8
        for y, row in enumerate(glyph_mask(ch)):
            for x, on in enumerate(row):
                if on:
                    img.putpixel((ox + x, oy + y), (255, 255, 255, 255))
    return img


def large_atlas(scale: int = 3) -> Image.Image:
    """Banner glyphs: scaled, brass gradient fill, dark outline, 1px bevel highlight."""
    gw, gh = 5 * scale + 2, 7 * scale + 2       # glyph + outline
    cw, ch = gw + 1, gh + 1
    img = _sheet(cw, ch)
    ramp = [palette.rgb(n) for n in ("sodium_4", "sodium_3", "sodium_3", "sodium_2", "sodium_1")]
    ink = palette.rgb("ink") + (255,)
    for i, glyph in enumerate(CHARSET):
        ox, oy = (i % COLUMNS) * cw, (i // COLUMNS) * ch
        mask = glyph_mask(glyph)
        fill = [[False] * gw for _ in range(gh)]
        for y in range(7):
            for x in range(5):
                if mask[y][x]:
                    for sy in range(scale):
                        for sx in range(scale):
                            fill[1 + y * scale + sy][1 + x * scale + sx] = True
        for y in range(gh):
            for x in range(gw):
                if fill[y][x]:
                    band = min(len(ramp) - 1, (y - 1) * len(ramp) // (7 * scale))
                    colour = ramp[band]
                    if y > 0 and not fill[y - 1][x]:
                        colour = palette.rgb("chalk")
                    img.putpixel((ox + x, oy + y), colour + (255,))
                elif any(0 <= y + dy < gh and 0 <= x + dx < gw and fill[y + dy][x + dx]
                         for dy in (-1, 0, 1) for dx in (-1, 0, 1)):
                    img.putpixel((ox + x, oy + y), ink)
    return img


def generate(assets: Path) -> None:
    folder = assets / "Resources" / "UI"
    folder.mkdir(parents=True, exist_ok=True)
    for name, image, cell, glyph in (("font_small", small_atlas(), (6, 8), (5, 7)),
                                     ("font_large", large_atlas(), (18, 24), (17, 23))):
        image.save(folder / f"{name}.png", optimize=True)
        meta = {"$comment": "Generated by Tools/Art/generate.py. Monospaced; glyphs in CHARSET order, row-major.",
                "image": f"{name}.png", "cell": list(cell), "glyph": list(glyph), "advance": cell[0],
                "columns": COLUMNS, "charset": CHARSET}
        (folder / f"{name}.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"font: {len(CHARSET)} glyphs")
